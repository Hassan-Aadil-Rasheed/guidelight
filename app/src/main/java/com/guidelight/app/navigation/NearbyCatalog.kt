    NearbyCategory.CHEMIST -> listOf("pharmacy")
    NearbyCategory.SHOPS, NearbyCategory.GROCERIES -> listOf("convenience store", "supermarket")
    NearbyCategory.FOOD -> listOf("restaurant", "cafe")
    NearbyCategory.CLINIC -> listOf("clinic", "doctors")
    NearbyCategory.TEMPLE, NearbyCategory.MANDIR, NearbyCategory.BUDDHIST_TEMPLE -> listOf("temple")
    NearbyCategory.MOSQUE -> listOf("mosque")
    NearbyCategory.GURDWARA -> listOf("gurdwara")
    NearbyCategory.WORSHIP -> listOf("place of worship")
    NearbyCategory.TOILET -> listOf("toilets")
    NearbyCategory.METRO -> listOf("subway station", "subway entrance")
    NearbyCategory.TRAIN_STATION -> listOf("railway station")
    NearbyCategory.TAXI -> listOf("taxi")
    NearbyCategory.OPTICIAN -> listOf("optician")
    NearbyCategory.LAB -> listOf("laboratory")
    NearbyCategory.FRUIT_VEG -> listOf("greengrocer")
    NearbyCategory.DAIRY -> listOf("dairy")
    NearbyCategory.MARKET -> listOf("marketplace")
    NearbyCategory.CLOTHES -> listOf("clothes")
